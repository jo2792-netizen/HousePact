"use client";

import { useState } from "react";
import { Icon } from "@/components/icons";
import { Logo } from "@/components/ui";
import { buildAgreement, longDate, roman, stamp, type Answers, type Block, type Household, type Table } from "@/lib/agreement";

type Props = {
  household: Household;
  answers: Answers;
  signatures: (string | null)[]; // when each roommate signed, or null
  onSign: (i: number) => void;
  onUnsign: (i: number) => void;
  me: number; // only you can sign on this device; everyone else is invited to sign on their own
};

/** The generated Residential Roommate Agreement, styled as a paper document. */
export function AgreementDocument({ household, answers, signatures, onSign, onUnsign, me }: Props) {
  const doc = buildAgreement(household, answers);
  const names = household.names;
  const signed = names.filter((_, i) => signatures[i]).length;
  const executed = signed === names.length;

  return (
    <article className="rounded-2xl bg-surface px-4 py-8 font-serif text-callout leading-relaxed text-label lining-nums print:rounded-none print:p-0">
      {/* Header */}
      <header className="flex flex-col items-center gap-4 border-b-2 border-label pb-6 text-center">
        <div className="font-sans">
          <Logo size="lg" />
        </div>
        <h1 className="font-serif text-title2 font-semibold tracking-wide uppercase">Residential Roommate Agreement</h1>
        <dl className="grid grid-cols-[auto_auto] gap-x-4 text-subhead">
          <dt className="text-right text-secondary">Agreement No.</dt>
          <dd className="text-left">{doc.id}</dd>
          <dt className="text-right text-secondary">Effective Date</dt>
          <dd className="text-left">{longDate(household.effective)}</dd>
          <dt className="text-right text-secondary">Status</dt>
          <dd className="text-left font-semibold">{executed ? "Fully Executed" : `Awaiting Signatures (${signed} of ${names.length} signed)`}</dd>
        </dl>
      </header>

      {/* Preamble */}
      <section className="mt-8 flex flex-col gap-4">
        {doc.preamble.map((p) => (
          <p key={p}>
            {p}
          </p>
        ))}
      </section>

      {/* Articles */}
      {doc.articles.map((article, ai) => (
        <section key={article.title} className="mt-10">
          <h2 className="mb-4 break-after-avoid text-center font-serif text-body font-semibold tracking-wide uppercase">
            Article {roman(ai)}. {article.title}
          </h2>
          <div className="flex flex-col gap-4">
            {article.sections.map((section, si) => (
              <div key={section.title} className="flex flex-col gap-4">
                {section.blocks.map((block, bi) => (
                  <DocBlock key={bi} block={block} lead={bi === 0 ? `${ai + 1}.${si + 1} ${section.title}.` : undefined} />
                ))}
              </div>
            ))}
          </div>
        </section>
      ))}

      {/* Signatures */}
      <section className="mt-12 break-inside-avoid">
        <h2 className="mb-4 text-center font-serif text-body font-semibold tracking-wide uppercase">Signatures</h2>
        <p>
          IN WITNESS WHEREOF, the Roommates have signed this Agreement, effective as of the Effective Date, on the dates written
          below.
        </p>
        <div className="mt-6 grid gap-8">
          {names.map((name, i) => (
            <SignatureLine
              key={i}
              name={name}
              email={i === me ? undefined : household.emails?.[i]}
              signedAt={signatures[i] ?? null}
              onSign={() => onSign(i)}
              onUnsign={() => onUnsign(i)}
            />
          ))}
        </div>
        {executed && (
          <p className="mt-8 flex items-center justify-center gap-2 border-2 border-label py-2 font-semibold tracking-widest uppercase">
            <Icon name="check" className="size-5" />
            Fully Executed
          </p>
        )}
      </section>

      {/* Footer */}
      <footer className="mt-12 border-t border-separator pt-4 text-center text-subhead text-secondary">
        <p>This agreement is between the Roommates and does not modify the lease with the landlord. It is not legal advice.</p>
        <p className="mt-1">
          {doc.id} · Generated by Housepact
        </p>
      </footer>
    </article>
  );
}

function DocBlock({ block, lead }: { block: Block; lead?: string }) {
  if ("p" in block) {
    return (
      <p>
        {lead && <strong className="font-semibold">{lead} </strong>}
        {block.p}
      </p>
    );
  }
  if ("list" in block) {
    return (
      <ol className="flex flex-col gap-2 pl-8">
        {block.list.map((item, i) => (
          <li key={i}>
            <span className="-ml-8 inline-block w-8">({String.fromCharCode(97 + i)})</span>
            {item}
          </li>
        ))}
      </ol>
    );
  }
  return <DocTable table={block.table} />;
}

function DocTable({ table }: { table: Table }) {
  return (
    <figure className="my-2 break-inside-avoid overflow-x-auto">
      <figcaption className="mb-2 text-center text-subhead font-semibold">{table.caption}</figcaption>
      <table className="w-full border-collapse text-subhead">
        <thead>
          <tr>
            {table.head.map((h) => (
              <th key={h} className="border border-secondary bg-fill p-2 text-left font-semibold print:bg-transparent">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {table.rows.map((row, r) => (
            <tr key={r}>
              {row.map((cell, c) => (
                <td key={c} className={`border border-secondary p-2 align-top ${/^\$|%$/.test(cell) ? "text-right tabular-nums" : ""}`}>
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
        {table.foot && (
          <tfoot>
            <tr>
              {table.foot.map((cell, c) => (
                <td key={c} className={`border border-secondary p-2 font-semibold ${c > 0 ? "text-right tabular-nums" : ""}`}>
                  {cell}
                </td>
              ))}
            </tr>
          </tfoot>
        )}
      </table>
      {table.note && <p className="mt-2 text-subhead text-secondary italic">{table.note}</p>}
    </figure>
  );
}

const clean = (s: string) => s.trim().replace(/\s+/g, " ").toLowerCase();

/** One roommate's signature: type your name to sign; it then appears in a script font with a timestamp. */
/**
 * One roommate's signature. Your own line has a type-to-sign box. An invited roommate's line
 * (one with an email) shows that they're waiting to sign on their own phone, with a Resend Invite button.
 */
function SignatureLine({ name, email, signedAt, onSign, onUnsign }: {
  name: string;
  email?: string;
  signedAt: string | null;
  onSign: () => void;
  onUnsign: () => void;
}) {
  const [typed, setTyped] = useState(name); // pre-filled for the demo
  const [resent, setResent] = useState(false);
  const matches = clean(typed) === clean(name);

  return (
    <div className="flex flex-col gap-1 break-inside-avoid">
      <div className="flex h-16 items-end border-b border-label pb-1">
        {signedAt && <span className="font-script text-large-title leading-none">{name}</span>}
      </div>
      <p className="text-subhead text-secondary">Signature</p>
      <p>
        <span className="text-secondary">Printed Name: </span>
        {name}
      </p>
      <p>
        <span className="text-secondary">Date: </span>
        {signedAt ? stamp(signedAt) : "____________________"}
      </p>

      {email && !signedAt ? (
        <div className="mt-2 flex flex-col gap-2 font-sans print:hidden">
          <p className="flex flex-wrap items-center gap-2 text-subhead text-secondary">
            <span className="rounded-md bg-fill px-2 py-1 font-semibold">Invited</span>
            {email} · Waiting to sign
          </p>
          <button
            className="link self-start"
            onClick={() => {
              setResent(true);
              setTimeout(() => setResent(false), 2500);
            }}
          >
            <Icon name={resent ? "check" : "reset"} className="size-4" />
            {resent ? "Invite Sent" : "Resend Invite"}
          </button>
        </div>
      ) : email ? (
        <p className="flex flex-wrap items-center gap-2 font-sans text-subhead text-secondary print:hidden">
          <Icon name="check" className="size-4 text-success" />
          Signed on their own device.
        </p>
      ) : signedAt ? (
        <p className="flex flex-wrap items-center gap-2 font-sans text-subhead text-secondary print:hidden">
          <Icon name="check" className="size-4 text-success" />
          Signed electronically.
          <button className="link" onClick={onUnsign}>
            Undo Signature
          </button>
        </p>
      ) : (
        <form
          className="mt-2 flex flex-col gap-2 font-sans print:hidden"
          onSubmit={(e) => {
            e.preventDefault();
            if (matches) onSign();
          }}
        >
          <div className="flex gap-2">
            <input
              className="field text-callout"
              placeholder={`Type "${name}"`}
              aria-label={`Signature for ${name}`}
              value={typed}
              onChange={(e) => setTyped(e.target.value)}
            />
            <button disabled={!matches} className="btn w-auto">
              Sign
            </button>
          </div>
          {typed && !matches && (
            <p role="alert" className="flex items-center gap-2 text-subhead text-danger">
              <Icon name="alert" className="size-4 shrink-0" />
              This doesn&apos;t match the printed name. Type it exactly as shown above.
            </p>
          )}
        </form>
      )}
    </div>
  );
}
