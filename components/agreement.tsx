"use client";

import { useState } from "react";
import { buildAgreement, longDate, roman, stamp, type Answers, type Block, type Household, type Table } from "@/lib/agreement";

type Props = {
  household: Household;
  answers: Answers;
  signatures: (string | null)[]; // when each roommate signed, or null
  onSign: (i: number) => void;
  onUnsign: (i: number) => void;
};

/** The generated Residential Roommate Agreement, styled as a paper document. */
export function AgreementDocument({ household, answers, signatures, onSign, onUnsign }: Props) {
  const doc = buildAgreement(household, answers);
  const names = household.names;
  const signed = names.filter((_, i) => signatures[i]).length;
  const executed = signed === names.length;

  return (
    <article className="border border-line bg-white px-4 py-8 font-serif text-[16px] leading-relaxed text-ink lining-nums sm:px-12 sm:py-10 print:border-0 print:p-0 print:text-[11pt]">
      {/* Header */}
      <header className="flex flex-col items-center gap-2 border-b-2 border-ink pb-6 text-center">
        <div className="flex items-center gap-2 font-heading text-base font-semibold tracking-wide">
          <Logo />
          Housepact
        </div>
        <h1 className="font-serif text-[26px] font-semibold tracking-wide uppercase sm:text-[30px]">Residential Roommate Agreement</h1>
        <dl className="grid grid-cols-[auto_auto] gap-x-3 text-[15px]">
          <dt className="text-right text-muted">Agreement No.</dt>
          <dd className="text-left">{doc.id}</dd>
          <dt className="text-right text-muted">Effective Date</dt>
          <dd className="text-left">{longDate(household.effective)}</dd>
          <dt className="text-right text-muted">Status</dt>
          <dd className="text-left font-semibold">{executed ? "Fully Executed" : `Awaiting Signatures (${signed} of ${names.length} signed)`}</dd>
        </dl>
      </header>

      {/* Preamble */}
      <section className="mt-8 flex flex-col gap-4">
        {doc.preamble.map((p) => (
          <p key={p} className="sm:text-justify">
            {p}
          </p>
        ))}
      </section>

      {/* Articles */}
      {doc.articles.map((article, ai) => (
        <section key={article.title} className="mt-10">
          <h2 className="mb-4 break-after-avoid text-center font-serif text-[18px] font-semibold tracking-wide uppercase">
            Article {roman(ai)}. {article.title}
          </h2>
          <div className="flex flex-col gap-4">
            {article.sections.map((section, si) => (
              <div key={section.title} className="flex flex-col gap-3">
                {section.blocks.map((block, bi) => (
                  <DocBlock key={bi} block={block} lead={bi === 0 ? `${ai + 1}.${si + 1} ${section.title}.` : undefined} />
                ))}
              </div>
            ))}
          </div>
        </section>
      ))}

      {/* Signatures */}
      <section className="mt-12 break-inside-avoid">
        <h2 className="mb-4 text-center font-serif text-[18px] font-semibold tracking-wide uppercase">Signatures</h2>
        <p className="sm:text-justify">
          IN WITNESS WHEREOF, the Roommates have signed this Agreement, effective as of the Effective Date, on the dates written
          below.
        </p>
        <div className="mt-6 grid gap-8 sm:grid-cols-2">
          {names.map((name, i) => (
            <SignatureLine key={i} name={name} signedAt={signatures[i] ?? null} onSign={() => onSign(i)} onUnsign={() => onUnsign(i)} />
          ))}
        </div>
        {executed && (
          <p className="mt-8 border-2 border-ink py-2 text-center font-semibold tracking-widest uppercase">Fully Executed</p>
        )}
      </section>

      {/* Footer */}
      <footer className="mt-12 border-t border-line pt-4 text-center text-[14px] text-muted">
        <p>This agreement is between the Roommates and does not modify the lease with the landlord. It is not legal advice.</p>
        <p className="mt-1">
          {doc.id} · Generated by Housepact
        </p>
      </footer>
    </article>
  );
}

function DocBlock({ block, lead }: { block: Block; lead?: string }) {
  if ("p" in block) {
    return (
      <p className="sm:text-justify">
        {lead && <strong className="font-semibold">{lead} </strong>}
        {block.p}
      </p>
    );
  }
  if ("list" in block) {
    return (
      <ol className="flex flex-col gap-2 pl-8">
        {block.list.map((item, i) => (
          <li key={i} className="sm:text-justify">
            <span className="-ml-8 inline-block w-8">({String.fromCharCode(97 + i)})</span>
            {item}
          </li>
        ))}
      </ol>
    );
  }
  return <DocTable table={block.table} />;
}

function DocTable({ table }: { table: Table }) {
  return (
    <figure className="my-2 break-inside-avoid overflow-x-auto">
      <figcaption className="mb-2 text-center text-[15px] font-semibold">{table.caption}</figcaption>
      <table className="w-full border-collapse text-[14px] sm:text-[15px]">
        <thead>
          <tr>
            {table.head.map((h) => (
              <th key={h} className="border border-ink bg-paper px-2 py-1.5 text-left font-semibold sm:px-3 sm:py-2 print:bg-transparent">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {table.rows.map((row, r) => (
            <tr key={r}>
              {row.map((cell, c) => (
                <td key={c} className={`border border-ink px-2 py-1.5 align-top sm:px-3 sm:py-2 ${/^\$|%$/.test(cell) ? "text-right tabular-nums" : ""}`}>
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
        {table.foot && (
          <tfoot>
            <tr>
              {table.foot.map((cell, c) => (
                <td key={c} className={`border border-ink px-2 py-1.5 font-semibold sm:px-3 sm:py-2 ${c > 0 ? "text-right tabular-nums" : ""}`}>
                  {cell}
                </td>
              ))}
            </tr>
          </tfoot>
        )}
      </table>
      {table.note && <p className="mt-2 text-[14px] text-muted italic">{table.note}</p>}
    </figure>
  );
}

const clean = (s: string) => s.trim().replace(/\s+/g, " ").toLowerCase();

/** One roommate's signature: type your name to sign; it then appears in a script font with a timestamp. */
function SignatureLine({ name, signedAt, onSign, onUnsign }: { name: string; signedAt: string | null; onSign: () => void; onUnsign: () => void }) {
  const [typed, setTyped] = useState("");
  const matches = clean(typed) === clean(name);

  return (
    <div className="flex flex-col gap-1 break-inside-avoid">
      <div className="flex h-16 items-end border-b border-ink pb-1">
        {signedAt && <span className="font-script text-[34px] leading-none">{name}</span>}
      </div>
      <p className="text-[14px] text-muted">Signature</p>
      <p>
        <span className="text-muted">Printed Name: </span>
        {name}
      </p>
      <p>
        <span className="text-muted">Date: </span>
        {signedAt ? stamp(signedAt) : "____________________"}
      </p>

      {signedAt ? (
        <p className="font-sans text-sm text-muted print:hidden">
          Signed electronically.{" "}
          <button className="underline" onClick={onUnsign}>
            Undo
          </button>
        </p>
      ) : (
        <form
          className="mt-2 flex flex-col gap-2 font-sans print:hidden"
          onSubmit={(e) => {
            e.preventDefault();
            if (matches) onSign();
          }}
        >
          <div className="flex gap-2">
            <input
              className="field h-12 text-[16px]"
              placeholder={`Type "${name}"`}
              aria-label={`Signature for ${name}`}
              value={typed}
              onChange={(e) => setTyped(e.target.value)}
            />
            <button disabled={!matches} className="btn h-12 w-auto">
              Sign
            </button>
          </div>
          {typed && !matches && <p className="text-sm text-muted">Type the name exactly as printed above.</p>}
        </form>
      )}
    </div>
  );
}

/** The Housepact mark: a note with a check. */
export function Logo() {
  return (
    <svg viewBox="0 0 32 32" className="size-7" aria-hidden>
      <rect width="32" height="32" rx="7" fill="#FFD95A" />
      <path d="M9 16.5l4.5 4.5L23 11.5" fill="none" stroke="#1E2A3A" strokeWidth="3.2" strokeLinecap="round" strokeLinejoin="round" />
    </svg>
  );
}
